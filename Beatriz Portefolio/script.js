function atualizarProgressoScroll() {
    if (frameAtualizacaoScroll) {
        return;
    }

    frameAtualizacaoScroll = window.requestAnimationFrame(() => {
        frameAtualizacaoScroll = 0;
        const distanciaPercorrivel =
            document.documentElement.scrollHeight - window.innerHeight;
        const progresso = distanciaPercorrivel > 0
            ? Math.min(1, Math.max(0, window.scrollY / distanciaPercorrivel))
            : 0;
        const percentagem = Math.round(progresso * 100);

        readingProgress.style.setProperty("--reading-progress-value", String(progresso));
        readingProgress.setAttribute("aria-valuenow", String(percentagem));
        readingProgress.setAttribute(
            "aria-valuetext",
            `${percentagem}%`
        );
        const mostrarBotao = window.scrollY > 400;
        backToTopButton.hidden = !mostrarBotao;
        backToTopButton.classList.toggle("is-visible", mostrarBotao);
    });
}

