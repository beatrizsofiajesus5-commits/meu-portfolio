function executarOperacao(esquerdo, operador, direito) {
    if (operador === "+") return esquerdo + direito;
    if (operador === "-") return esquerdo - direito;
    if (operador === "*") return esquerdo * direito;
    return esquerdo / direito;
}

document.querySelector(".calculator-keys").addEventListener("click", (event) => {
    const button = event.target.closest("[data-calc]");
    if (!button) {
        return;
    }

    const action = button.dataset.calc;
    const value = button.dataset.value;
    calculatorStatus.textContent = "";

    if (action === "clear") {
        calculatorCurrent = "0";
        calculatorPrevious = null;
        calculatorOperator = null;
        calculatorWaitingForOperand = false;
    } else if (action === "digit") {
        calculatorCurrent = calculatorWaitingForOperand || calculatorCurrent === "0"
            ? value
            : `${calculatorCurrent}${value}`.slice(0, 12);
        calculatorWaitingForOperand = false;
    } else if (action === "decimal") {
        if (calculatorWaitingForOperand) {
            calculatorCurrent = "0.";
            calculatorWaitingForOperand = false;
        } else if (!calculatorCurrent.includes(".")) {
            calculatorCurrent += ".";
        }
    } else if (action === "delete") {
        calculatorCurrent = calculatorWaitingForOperand
            ? "0"
            : calculatorCurrent.slice(0, -1) || "0";
        calculatorWaitingForOperand = false;
    } else if (action === "operator") {
        if (calculatorOperator && !calculatorWaitingForOperand) {
            calculatorCurrent = String(Number(executarOperacao(
                calculatorPrevious,
                calculatorOperator,
                Number(calculatorCurrent)
            ).toPrecision(10)));
        }
        calculatorPrevious = Number(calculatorCurrent);
        calculatorOperator = value;
        calculatorWaitingForOperand = true;
    } else if (action === "equals" && calculatorOperator && calculatorPrevious !== null) {
        const resultado = executarOperacao(
            calculatorPrevious,
            calculatorOperator,
            Number(calculatorCurrent)
        );

        if (!Number.isFinite(resultado)) {
            calculatorStatus.textContent = traducoes[idiomaAtual].calculator_error;
            calculatorCurrent = "0";
        } else {
            calculatorCurrent = String(Number(resultado.toPrecision(10)));
        }

        calculatorPrevious = null;
        calculatorOperator = null;
        calculatorWaitingForOperand = true;
    }

    atualizarVisorCalculadora();
});

